/**
 * Controlled attack simulation.
 *
 * These events are synthetic telemetry, not network traffic. They exercise the
 * same ingestion, anomaly-scoring and detection path as a real sensor so an
 * operator can prove that brute-force, port-scan and beaconing rules fire and
 * appear in the dashboard. Every event is labelled `simulated` in `raw`.
 */

export const SIMULATION_SCENARIOS = ["brute_force", "port_scan", "suspicious_beacon", "suspicious_egress", "all"];

const MINUTE = 60 * 1000;

function iso(now, offsetMs) {
  return new Date(now - offsetMs).toISOString();
}

function raw(scenario, index) {
  return JSON.stringify({
    simulated: true,
    scenario,
    index,
    note: "Controlled detection-validation event generated by the Digital Twin Cyber War API.",
  });
}

function bruteForce(now, runId) {
  return Array.from({ length: 12 }, (_, index) => ({
    timestamp: iso(now, (11 - index) * 20 * 1000),
    source: "attack-simulation",
    host: "vpn-gateway-sim",
    event: "authentication_failed",
    action: "password_login",
    status: "deny",
    ip: "203.0.113.77",
    user: index % 3 === 0 ? "svc-backup" : index % 3 === 1 ? "admin" : "m.suhail",
    message: `Failed password for ${
      index % 3 === 1 ? "admin" : "svc-backup"
    } from 203.0.113.77 port ${51000 + index} ssh2 · simulation ${runId}`,
    raw: raw("brute_force", index),
  }));
}

function portScan(now, runId) {
  return Array.from({ length: 20 }, (_, index) => ({
    timestamp: iso(now, (19 - index) * 3 * 1000),
    source: "attack-simulation",
    host: "edge-fw-sim",
    event: "network_flow",
    action: "syn_probe",
    status: "deny",
    ip: "203.0.113.88",
    user: "",
    message: `SYN probe from 203.0.113.88 to 10.20.0.10:${20 + index} denied · simulation ${runId}`,
    raw: raw("port_scan", index),
    dstIp: "10.20.0.10",
    dstPort: 20 + index,
    proto: "tcp",
    bytes: 60,
    direction: "inbound",
    sensor: "simulation",
  }));
}

function beaconing(now, runId) {
  return Array.from({ length: 9 }, (_, index) => ({
    timestamp: iso(now, (8 - index) * 30 * 1000),
    source: "attack-simulation",
    host: "ws-sim-beacon",
    event: "network_flow",
    action: "tls_session",
    status: "allow",
    ip: "10.20.4.66",
    user: "j.weber",
    message: `TLS session 10.20.4.66:${52000 + index} → 198.51.100.66:443 612 B · simulation ${runId}`,
    raw: raw("suspicious_beacon", index),
    dstIp: "198.51.100.66",
    dstPort: 443,
    proto: "tcp",
    bytes: 612,
    durationMs: 180,
    direction: "outbound",
    sensor: "simulation",
  }));
}

function blockedEgress(now, runId) {
  return Array.from({ length: 7 }, (_, index) => ({
    timestamp: iso(now, (6 - index) * 25 * 1000),
    source: "attack-simulation",
    host: "ws-sim-egress",
    event: "egress_blocked",
    action: "deny",
    status: "deny",
    ip: "10.20.4.67",
    user: "svc-app01",
    message: `Outbound TLS to 198.51.100.${10 + index}:443 denied by egress-filter policy · simulation ${runId}`,
    raw: raw("suspicious_egress", index),
    dstIp: `198.51.100.${10 + index}`,
    dstPort: 443,
    proto: "tcp",
    direction: "outbound",
    sensor: "simulation",
  }));
}

export function buildAttackSimulation(scenario = "all", { now = Date.now(), runId = "manual" } = {}) {
  const selected = scenario === "all" ? ["brute_force", "port_scan", "suspicious_beacon", "suspicious_egress"] : [scenario];
  const builders = {
    brute_force: bruteForce,
    port_scan: portScan,
    suspicious_beacon: beaconing,
    suspicious_egress: blockedEgress,
  };
  const events = selected.flatMap((name) => builders[name](now, runId));
  return { events, scenarios: selected };
}
