import { config } from "../config.js";

/**
 * OpenAI-compatible chat completion client for the HUNTER assistant.
 *
 * The endpoint is configurable so an operator can use a hosted model, an
 * internal gateway, vLLM or Ollama. When no endpoint is configured the API
 * returns an explicit "not configured" error; there is no canned local answer
 * pretending to be a model response.
 */

export function assistantStatus() {
  const configured = Boolean(config.assistant.baseUrl);
  let host = null;
  if (configured) {
    try {
      host = new URL(config.assistant.baseUrl).host;
    } catch {
      host = null;
    }
  }
  return {
    configured,
    mode: configured ? "live" : "unconfigured",
    model: config.assistant.model,
    endpointHost: host,
    maxTokens: config.assistant.maxTokens,
    timeoutMs: config.assistant.timeoutMs,
    note: configured
      ? "Answers are generated by the configured OpenAI-compatible endpoint and cite retrieved workspace evidence."
      : "Set HUNTER_LLM_BASE_URL and HUNTER_LLM_MODEL to enable natural-language analysis. No canned answers are returned.",
  };
}

function completionUrl(baseUrl) {
  const normalized = baseUrl.replace(/\/+$/, "");
  return normalized.endsWith("/chat/completions")
    ? normalized
    : `${normalized}/chat/completions`;
}

function extractMessage(body) {
  const message = body?.choices?.[0]?.message;
  if (!message) return "";
  if (typeof message.content === "string") return message.content;
  if (Array.isArray(message.content)) {
    return message.content
      .map((part) => (typeof part === "string" ? part : part?.text || ""))
      .join("\n");
  }
  return "";
}

export async function askHunter({ question, context, fetchImpl = globalThis.fetch }) {
  if (!config.assistant.baseUrl) {
    const error = new Error(
      "The HUNTER assistant is not configured. Set HUNTER_LLM_BASE_URL and HUNTER_LLM_MODEL on the API server."
    );
    error.code = "assistant_not_configured";
    throw error;
  }
  if (typeof fetchImpl !== "function") {
    const error = new Error("No fetch implementation is available for the assistant.");
    error.code = "assistant_unavailable";
    throw error;
  }

  const system = [
    "You are HUNTER, a defensive security analyst assistant inside a cyber-range workspace.",
    "Answer only from the supplied evidence. Every factual claim must cite one or more source references such as [S1] or [S3].",
    "If the evidence is insufficient, say exactly what is missing. Never invent hosts, users, IP addresses, timestamps, detections, verdicts or incidents.",
    "The telemetry anomaly score comes from an isolation forest trained on this workspace. Explain that it indicates statistical deviation, not proof of compromise.",
    "Recommend defensive containment only through the approval-gated response playbooks. Never provide offensive instructions.",
    "Prefer a concise structure: assessment, evidence, recommended next action. Keep it under 450 words.",
  ].join(" ");

  const user = [
    `Investigator question: ${question}`,
    "",
    "Retrieved workspace evidence (the only facts you may use):",
    context,
    "",
    "Cite sources by their ref value. If a source list is empty, say the workspace has no matching evidence.",
  ].join("\n");

  const headers = { "Content-Type": "application/json", Accept: "application/json" };
  if (config.assistant.apiKey) headers.Authorization = `Bearer ${config.assistant.apiKey}`;

  let response;
  try {
    response = await fetchImpl(completionUrl(config.assistant.baseUrl), {
      method: "POST",
      headers,
      body: JSON.stringify({
        model: config.assistant.model,
        temperature: 0.2,
        max_tokens: config.assistant.maxTokens,
        messages: [
          { role: "system", content: system },
          { role: "user", content: user },
        ],
      }),
      signal: AbortSignal.timeout(config.assistant.timeoutMs),
    });
  } catch (error) {
    const wrapped = new Error(
      error?.name === "TimeoutError"
        ? "The configured language model did not respond before the timeout."
        : `The language model endpoint could not be reached: ${error.message}`
    );
    wrapped.code = "assistant_upstream_error";
    throw wrapped;
  }

  const text = await response.text();
  let body = null;
  try {
    body = text ? JSON.parse(text) : null;
  } catch {
    body = null;
  }

  if (!response.ok) {
    const error = new Error(
      String(body?.error?.message || body?.message || `Language model returned HTTP ${response.status}.`).slice(
        0,
        300
      )
    );
    error.code = "assistant_upstream_error";
    error.status = response.status;
    throw error;
  }

  const answer = extractMessage(body).trim();
  if (!answer) {
    const error = new Error("The language model returned an empty response.");
    error.code = "assistant_empty_response";
    throw error;
  }

  return {
    answer,
    model: body?.model || config.assistant.model,
    provider: assistantStatus().endpointHost || "configured endpoint",
    usage: body?.usage || null,
    generatedAt: new Date().toISOString(),
  };
}
